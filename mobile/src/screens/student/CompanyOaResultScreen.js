import { StyleSheet, Text, View } from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import Screen from '../../components/Screen';
import { AppButton, Card } from '../../components/Ui';
import { colors, spacing } from '../../constants/theme';

export default function CompanyOaResultScreen({ navigation, route }) {
  const { result = {}, title = 'Company OA', autoSubmitted, submissionReason } = route.params || {};
  const foregroundSubmitted = submissionReason === 'foreground-switches';
  const statusTitle = foregroundSubmitted
    ? 'Assessment auto-submitted'
    : autoSubmitted
      ? 'Time is up — assessment submitted'
      : 'Assessment submitted';

  return (
    <Screen>
      <View style={styles.hero}>
        <View style={styles.icon}><Ionicons name="checkmark" size={36} color={colors.white} /></View>
        <Text style={styles.title}>{statusTitle}</Text>
        <Text style={styles.subtitle}>{title}</Text>
      </View>
      <Card>
        <Text style={styles.score}>{result.pct ?? 0}%</Text>
        <Text style={styles.caption}>{result.score ?? 0} / {result.maxScore ?? 0} marks · Grade {result.grade || '—'}</Text>
        <View style={styles.stats}>
          <Stat label="Correct" value={result.correct ?? 0} color={colors.success} />
          <Stat label="Wrong" value={result.wrong ?? 0} color={colors.danger} />
          <Stat label="Skipped" value={result.skipped ?? 0} color={colors.warning} />
        </View>
      </Card>
      <Text style={styles.note}>This outcome is generated by the assessment’s configured answer logic and is intended for practice feedback.</Text>
      <AppButton title="Back to Company OA" onPress={() => navigation.navigate('CompanyOaList', { refreshKey: Date.now() })} style={styles.button} />
    </Screen>
  );
}

function Stat({ label, value, color }) {
  return <View style={styles.stat}><Text style={[styles.statValue, { color }]}>{value}</Text><Text style={styles.statLabel}>{label}</Text></View>;
}

const styles = StyleSheet.create({
  hero: { alignItems: 'center', paddingVertical: spacing.lg },
  icon: { width: 72, height: 72, borderRadius: 36, backgroundColor: colors.success, justifyContent: 'center', alignItems: 'center' },
  title: { color: colors.text, fontSize: 23, fontWeight: '900', textAlign: 'center', marginTop: 13 },
  subtitle: { color: colors.muted, marginTop: 5, textAlign: 'center' },
  score: { textAlign: 'center', color: colors.primary, fontWeight: '900', fontSize: 38 },
  caption: { textAlign: 'center', color: colors.muted, marginTop: 4 },
  stats: { flexDirection: 'row', marginTop: 18, paddingTop: 14, borderTopWidth: 1, borderColor: colors.border },
  stat: { flex: 1, alignItems: 'center' },
  statValue: { fontSize: 20, fontWeight: '900' },
  statLabel: { color: colors.muted, fontSize: 12, marginTop: 3 },
  note: { color: colors.muted, lineHeight: 18, fontSize: 12, marginTop: 14 },
  button: { marginTop: spacing.lg },
});
